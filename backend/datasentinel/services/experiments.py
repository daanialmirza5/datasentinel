"""Fault-injection experiments: inject → detect → evaluate → simulate impact.

Isolation guarantees:
* The base version is read-only. Generated data is written to a separate ``lab`` dataset that is
  hidden from normal listings and lineage, so originals are never overwritten.
* The injector writes the ground truth; detection receives only the base and modified tables.
* Re-running with the same seed reproduces byte-identical data (verified via SHA-256).
"""

from __future__ import annotations

import time
from datetime import timedelta
from typing import Any

import numpy as np
from sqlalchemy import select
from sqlalchemy.orm import Session

from datasentinel.config import Settings
from datasentinel.detection.signals import SEVERITY_RANK
from datasentinel.errors import NotFoundError, ValidationFailed
from datasentinel.lab.detector import run_detection
from datasentinel.lab.evaluation import evaluate
from datasentinel.lab.faults import FaultContext, FaultError, inject
from datasentinel.lineage.graph import downstream
from datasentinel.models import Dataset, DatasetVersion, Experiment, LineageAsset, QualityRule, new_id, utcnow
from datasentinel.services import datasets as ds
from datasentinel.services.impact import _classify
from datasentinel.services.lineage import asset_health, build_graph
from datasentinel.services.profiles import get_or_compute_profile
from datasentinel.services.validation import enabled_rules, reference_resolver

BREAKING = {"column_removed", "type_change"}


def foreign_key_columns(session: Session, dataset_id: str) -> list[str]:
    rules = session.scalars(
        select(QualityRule).where(QualityRule.dataset_id == dataset_id, QualityRule.rule_type == "foreign_key")
    )
    return sorted({r.column_name for r in rules if r.column_name})


def fault_context(session: Session, settings: Settings, version: DatasetVersion, seed: int) -> FaultContext:
    profile, _ = get_or_compute_profile(session, settings, version)
    return FaultContext(
        ds.load_table(settings, version),
        profile.profile,
        np.random.default_rng(seed),
        foreign_key_columns(session, version.dataset_id),
    )


def simulated_state(detection: dict[str, Any]) -> str:
    signals = detection["signals"]
    if any(s["source"] == "rule" for s in signals) or any(
        s["category"] in BREAKING and SEVERITY_RANK[s["severity"]] >= SEVERITY_RANK["high"] for s in signals
    ):
        return "failing"
    if any(SEVERITY_RANK[s["severity"]] >= SEVERITY_RANK["medium"] for s in signals):
        return "anomalous"
    return "passing"


def simulated_impact(session: Session, dataset: Dataset, state: str) -> dict[str, Any]:
    asset = session.scalar(select(LineageAsset).where(LineageAsset.dataset_id == dataset.id))
    if asset is None:
        return {"asset_id": None, "simulated_origin_state": state, "impacted": []}
    graph = build_graph(session)
    impacted = []
    for node_id, info in downstream(graph, asset.id).items():
        node = session.get(LineageAsset, node_id)
        own = asset_health(session, node)["state"]
        impacted.append(
            {
                "id": node_id,
                "name": node.name,
                "kind": node.kind,
                "distance": info["distance"],
                "path": [graph.nodes[p]["name"] for p in info["path"]],
                "path_ids": info["path"],
                "classification": _classify(state, info["distance"], own),
            }
        )
    impacted.sort(key=lambda i: (i["distance"], i["name"]))
    return {"asset_id": asset.id, "simulated_origin_state": state, "impacted": impacted}


def _execute(
    session: Session, settings: Settings, experiment: Experiment, dataset: Dataset, base: DatasetVersion
) -> None:
    started = time.perf_counter()
    ctx = fault_context(session, settings, base, experiment.seed)
    try:
        modified, truth = inject(experiment.fault_type, ctx, experiment.params)
    except (FaultError, ValueError) as exc:
        raise ValidationFailed(str(exc)) from exc
    content = modified.to_csv(index=False, lineterminator="\n", na_rep="").encode("utf-8")

    lab = Dataset(
        name=f"{dataset.name} · lab {experiment.id[-6:]}"[:120],
        kind="lab",
        description=f"Generated by experiment {experiment.id} ({experiment.fault_type}, seed "
        f"{experiment.seed}). Synthetic modification of version {base.version_number}.",
    )
    session.add(lab)
    session.flush()
    version = ds.import_version(
        session,
        settings,
        content=content,
        filename=f"{experiment.fault_type}.csv",
        dataset_id=lab.id,
        origin="fault_injection",
        kind="lab",
        parent_version_id=base.id,
        run_analysis=False,
    )
    cand_profile, _ = get_or_compute_profile(session, settings, version)
    detection = run_detection(
        ctx.table,
        ds.load_table(settings, version),
        ctx.profile,
        cand_profile.profile,
        enabled_rules(session, dataset.id),
        settings,
        reference_resolver(session, settings),
    )
    experiment.lab_dataset_id = lab.id
    experiment.result_version_id = version.id
    experiment.params = truth["params"]
    experiment.ground_truth = truth
    experiment.detection = detection
    experiment.evaluation = {
        **evaluate(truth, detection["signals"]),
        "simulated_impact": simulated_impact(session, dataset, simulated_state(detection)),
        "modified_sha256": version.sha256,
        "base_rows": base.row_count,
        "modified_rows": version.row_count,
    }
    experiment.status = "completed"
    experiment.duration_ms = round((time.perf_counter() - started) * 1000, 2)
    if settings.experiment_retention_hours > 0:
        experiment.expires_at = utcnow() + timedelta(hours=settings.experiment_retention_hours)
    session.flush()


def create_experiment(
    session: Session,
    settings: Settings,
    *,
    dataset_id: str,
    fault_type: str,
    params: dict[str, Any],
    seed: int,
    version_id: str | None = None,
) -> Experiment:
    dataset = ds.get_dataset(session, dataset_id)
    if dataset.kind == "lab":
        raise ValidationFailed("Run experiments on user or sample datasets, not on generated lab data.")
    base = ds.resolve_version(session, dataset, version_id)
    experiment = Experiment(
        id=new_id("exp"),
        dataset_id=dataset.id,
        base_version_id=base.id,
        fault_type=fault_type,
        params=dict(params),
        seed=seed,
        status="running",
    )
    session.add(experiment)
    session.flush()
    _execute(session, settings, experiment, dataset, base)
    return experiment


def _remove_lab_data(session: Session, settings: Settings, experiment: Experiment) -> None:
    if experiment.lab_dataset_id:
        lab = session.get(Dataset, experiment.lab_dataset_id)
        experiment.lab_dataset_id = None
        experiment.result_version_id = None
        session.flush()
        if lab is not None and lab.kind == "lab":
            ds.delete_dataset(session, settings, lab)


def regenerate(session: Session, settings: Settings, experiment: Experiment, seed: int | None = None) -> Experiment:
    dataset = ds.get_dataset(session, experiment.dataset_id)
    base = session.get(DatasetVersion, experiment.base_version_id)
    if base is None:
        raise NotFoundError("The experiment's base version no longer exists.")
    _remove_lab_data(session, settings, experiment)
    if seed is not None:
        experiment.seed = seed
    experiment.created_at = utcnow()
    _execute(session, settings, experiment, dataset, base)
    return experiment


def delete_experiment(session: Session, settings: Settings, experiment: Experiment) -> None:
    _remove_lab_data(session, settings, experiment)
    session.delete(experiment)
    session.flush()


def get_experiment(session: Session, experiment_id: str) -> Experiment:
    experiment = session.get(Experiment, experiment_id)
    if experiment is None:
        raise NotFoundError(f"Experiment '{experiment_id}' not found")
    return experiment


def purge_expired(session: Session, settings: Settings) -> int:
    """Delete experiments (and their generated lab data) past their retention deadline."""
    now = utcnow()
    expired = list(
        session.scalars(select(Experiment).where(Experiment.expires_at.is_not(None), Experiment.expires_at < now))
    )
    for experiment in expired:
        delete_experiment(session, settings, experiment)
    return len(expired)
