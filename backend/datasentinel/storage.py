"""File storage for dataset versions.

Storage keys are generated by the server (``<version id>.<format>``); user-supplied filenames are
kept only as display metadata and never influence a path. Every key is validated against a strict
pattern and the resolved path is checked to stay inside the storage root.
"""

from __future__ import annotations

import os
import re
import tempfile
from pathlib import Path

KEY_PATTERN = re.compile(r"^[a-z]{2,8}_[0-9a-f]{16}\.(csv|json|jsonl)$")


class StorageError(Exception):
    pass


class Storage:
    def __init__(self, root: Path) -> None:
        self.root = root.resolve()

    def path_for(self, key: str) -> Path:
        if not KEY_PATTERN.fullmatch(key):
            raise StorageError("Invalid storage key")
        path = (self.root / key).resolve()
        if path.parent != self.root:
            raise StorageError("Storage key escapes the storage root")
        return path

    def write(self, key: str, content: bytes) -> Path:
        path = self.path_for(key)
        self.root.mkdir(parents=True, exist_ok=True)
        if path.exists():
            raise StorageError("Refusing to overwrite an existing stored file")
        fd, tmp = tempfile.mkstemp(dir=self.root, prefix=".upload-")
        try:
            with os.fdopen(fd, "wb") as handle:
                handle.write(content)
            os.replace(tmp, path)
        except BaseException:
            Path(tmp).unlink(missing_ok=True)
            raise
        return path

    def read(self, key: str) -> bytes:
        path = self.path_for(key)
        if not path.exists():
            raise StorageError("Stored file is missing")
        return path.read_bytes()

    def exists(self, key: str) -> bool:
        return self.path_for(key).exists()

    def delete(self, key: str) -> None:
        self.path_for(key).unlink(missing_ok=True)

    def usage_bytes(self) -> int:
        if not self.root.exists():
            return 0
        return sum(p.stat().st_size for p in self.root.iterdir() if p.is_file())
